import path from 'path';
import fs from 'fs';

const rendererDir = path.resolve(import.meta.dirname, '..', 'renderer');
const presetsDir = path.join(rendererDir, 'presets');
const outFile = path.join(rendererDir, 'templates-presets.js');

const presetsByTemplate = {};
if (fs.existsSync(presetsDir)) {
  const templateDirs = fs.readdirSync(presetsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory());

  for (const dir of templateDirs) {
    const templateId = dir.name;
    const files = fs.readdirSync(path.join(presetsDir, templateId))
      .filter((f) => f.endsWith('.json'))
      .sort();

    const presetArray = [];
    for (const file of files) {
      const filePath = path.join(presetsDir, templateId, file);
      const json = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
      presetArray.push(json);
    }
    presetsByTemplate[templateId] = presetArray;
  }
}

const js = `// Auto-generated by build-presets-qawaleb.mjs — do not edit directly
// Source JSON files: renderer/presets/<template-id>/*.json
window.QAWALEB_TEMPLATE_PRESETS_EXT = ${JSON.stringify(presetsByTemplate, null, 2)};
`;

fs.writeFileSync(outFile, js, 'utf-8');
console.log(`Qawaleb presets built at: ${outFile}`);
